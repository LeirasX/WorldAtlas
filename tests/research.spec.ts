import { expect, test } from '@playwright/test'

test('local WDI indicators appear throughout the shared application', async ({ page }) => {
  await page.goto('./#/countries/PRT')
  await expect(page.getByRole('button', { name: /^Life expectancy at birth/ })).toBeVisible()
  await page.getByRole('button', { name: /^Life expectancy at birth/ }).click()
  await expect(page.getByRole('dialog')).toContainText('not individually verified')
  await expect(page.getByRole('dialog')).toContainText('not individually assessed')
  await expect(page.getByRole('dialog')).toContainText('SP.DYN.LE00.IN')
  await page.getByRole('button', { name: 'Close metric details' }).click()
  await expect(page.getByRole('button', { name: /^Net salary · unverified/ })).toBeVisible()
  await page.goto('./#/explore')
  await page.getByRole('button', { name: 'Columns', exact: true }).click()
  await page.getByRole('checkbox', { name: 'Life expectancy at birth, total (years) · WDI' }).check()
  await page.getByRole('button', { name: 'Columns', exact: true }).click()
  await expect(page.getByRole('columnheader', { name: 'Life expectancy at birth, total (years) · WDI' })).toBeAttached()
  await page.getByRole('combobox', { name: 'Statistics metric' }).selectOption('wb_life_expectancy_years')
  await expect(page.locator('.statistics')).toContainText('194/195')
  await page.getByRole('checkbox', { name: 'Compare Portugal', exact: true }).check()
  await page.getByRole('checkbox', { name: 'Compare Spain', exact: true }).check()
  await page.getByRole('button', { name: 'Compare (2/5)' }).click()
  await expect(page.getByRole('dialog')).toContainText('Life expectancy at birth, total (years) · WDI')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy()
  await page.getByRole('button', { name: 'Close comparison' }).click()
  await page.goto('./#/map')
  await page.getByRole('combobox', { name: 'Color by metric' }).selectOption('wb_life_expectancy_years')
  await expect(page.locator('.map-legend')).toContainText('Life expectancy')
})
