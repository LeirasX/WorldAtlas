test('sourced content packs are imported transactionally and become searchable', async ({ page }) => {
  await page.goto('./#/world')
  const dataButton = page.getByRole('button', { name: 'Data & sources', exact: true }).first()
  if (await dataButton.isVisible()) await dataButton.click()
  else await page.getByRole('button', { name: 'Data and sources', exact: true }).click()
  await page.getByText('Import research articles and relationships', { exact: true }).click()
  const content = {
    version: 1,
    entities: [{ id: 'topic:imported-survey-note', kind: 'topic', title: 'Imported survey note', summary: 'A supplied note for testing the content importer.', body: 'Read the original source for its definition.', sources: [{ label: 'World Bank', url: 'https://data.worldbank.org/' }] }],
    relationships: [{ from: 'topic:imported-survey-note', to: 'country:PRT', label: 'has a supplied example in' }],
  }
  await page.getByLabel('Import knowledge JSON').setInputFiles({ name: 'research.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(content)) })
  await expect(page.getByRole('status')).toContainText('Knowledge imported and saved')
  await page.getByRole('button', { name: 'Close data details' }).click()
  await page.reload()
  await page.getByRole('button', { name: /Search ORBIS/ }).click()
  await page.getByRole('combobox', { name: 'Search ORBIS' }).fill('Imported survey note')
  await page.keyboard.press('Enter')
  await expect(page.getByRole('heading', { name: 'Imported survey note', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: /Portugal country/ })).toBeVisible()
})

test('map controls rotate and zoom the globe while preserving a usable phone layout', async ({ page }) => {
  await page.goto('./#/map')
  await page.getByRole('button', { name: 'Globe', exact: true }).click()
  await page.getByRole('combobox', { name: 'Zoom to country' }).selectOption('PRT')
  const svg = page.getByLabel('World map', { exact: true })
  const path = page.locator('.map-country.focused > path')
  const before = await path.getAttribute('d')
  await page.getByRole('button', { name: 'Zoom in', exact: true }).click()
  await expect(path).not.toHaveAttribute('d', before!)
  const box = await svg.boundingBox()
  expect(box).not.toBeNull()
  if (box) {
    const shapeBefore = await path.getAttribute('d')
    await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2)
    await page.mouse.down()
    await page.mouse.move(box.x + box.width / 2 + 40, box.y + box.height / 2 + 20, { steps: 5 })
    await page.mouse.up()
    await expect(path).not.toHaveAttribute('d', shapeBefore!)
  }
  await page.getByRole('button', { name: 'Use dark theme' }).click()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy()
})
