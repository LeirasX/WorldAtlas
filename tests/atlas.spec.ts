import { expect, test } from '@playwright/test'

test('search, open a profile, and select a country on the map', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('./')
  await expect(page.getByRole('heading', { name: 'Explore the world.' })).toBeVisible()
  await page.getByRole('button', { name: /Search countries/ }).click()
  await page.getByRole('combobox', { name: 'Search by country, alias, or code' }).fill('holland')
  await page.keyboard.press('Enter')
  await expect(page.getByRole('heading', { name: 'Netherlands' })).toBeVisible()
  await page.getByRole('button', { name: 'View on map' }).click()
  await expect(page.getByRole('heading', { name: 'World map' })).toBeVisible()
  await page.getByRole('combobox', { name: 'Color by metric' }).selectOption('population')
  await page.getByRole('button', { name: 'Netherlands', exact: true }).press('Enter')
  await expect(page).toHaveURL(/WorldAtlas\/#\/countries\/NLD/)
  expect(errors).toEqual([])
})

test('filter, sort, compare, expand, and export the public table', async ({ page }) => {
  await page.goto('./')
  await page.getByRole('button', { name: /Europe 44 countries/ }).click()
  await expect(page.getByText('44 of 195 countries')).toBeVisible()
  await page.getByRole('button', { name: 'Pop.', exact: true }).click()
  await expect(page.getByRole('columnheader', { name: 'Pop.' })).toHaveAttribute('aria-sort', 'ascending')
  await page.getByRole('button', { name: 'Filters', exact: true }).click()
  await page.getByRole('textbox', { name: 'Filter expression' }).fill('population>1M')
  await expect(page.getByRole('checkbox', { name: 'Compare Vatican City' })).toHaveCount(0)
  await page.getByRole('checkbox', { name: 'Compare Portugal', exact: true }).check()
  await page.getByRole('checkbox', { name: 'Compare Spain', exact: true }).check()
  await page.getByRole('button', { name: 'Compare (2/5)' }).click()
  await expect(page.getByRole('dialog', { name: 'Country comparison' })).toBeVisible()
  await page.getByRole('button', { name: 'Close comparison' }).click()
  await page.getByRole('button', { name: 'Expand table' }).click()
  await expect(page.getByRole('dialog', { name: 'Expanded country table' })).toBeVisible()
  await page.getByRole('button', { name: 'Exit expanded table' }).click()
  const download = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Export CSV' }).click()
  expect((await download).suggestedFilename()).toBe('worldatlas-explore.csv')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy()
})

test('public project subpath reloads and opens the map offline', async ({ page, context }) => {
  await page.goto('./')
  await page.evaluate(async () => { await navigator.serviceWorker.ready })
  await page.reload()
  await expect.poll(() => page.evaluate(() => Boolean(navigator.serviceWorker.controller))).toBeTruthy()
  await context.setOffline(true)
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Explore the world.' })).toBeVisible()
  await page.getByRole('button', { name: 'Open world map' }).click()
  await expect(page.getByRole('button', { name: 'Portugal', exact: true })).toBeAttached()
  await context.setOffline(false)
})
